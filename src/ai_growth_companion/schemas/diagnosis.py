"""Strict structured contracts for questions, observations, decisions, and actions."""

from enum import StrEnum
from typing import Literal, Self

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


class StrictSchema(BaseModel):
    """Reject undeclared fields so provider drift cannot silently enter the product."""

    model_config = ConfigDict(extra="forbid")


class Severity(StrEnum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class EvidenceStrength(StrEnum):
    WEAK = "weak"
    MEDIUM = "medium"
    STRONG = "strong"


class MasteryLevel(StrEnum):
    NO_CLUE = "no_clue"
    FRAGILE = "fragile"
    DEVELOPING = "developing"
    SOLID = "solid"


class UnderstandingLevel(StrEnum):
    NOVICE = "novice"
    DEVELOPING = "developing"
    PROFICIENT = "proficient"


class ActionType(StrEnum):
    REVIEW = "review"
    EXAMPLE = "example"
    PRACTICE = "practice"
    RE_LEARN = "re_learn"


def normalize_mastery_level(value: object) -> object:
    """Read the pre-v0.3 storage spelling while emitting the v0.3 spelling."""
    return MasteryLevel.NO_CLUE if value in {"not_evident", "no_clue"} else value


def normalize_action_type(value: object) -> object:
    """Read the pre-v0.3 storage spelling while emitting the v0.3 spelling."""
    return ActionType.RE_LEARN if value in {"re_explain", "re_learn"} else value


def storage_mastery_level(value: MasteryLevel | str) -> str:
    """Keep legacy SQLite CHECK constraints readable until a future table rebuild."""
    normalized = normalize_mastery_level(value)
    if normalized is MasteryLevel.NO_CLUE:
        return "not_evident"
    return str(getattr(normalized, "value", normalized))


def storage_action_type(value: ActionType | str) -> str:
    """Keep legacy SQLite CHECK constraints readable until a future table rebuild."""
    normalized = normalize_action_type(value)
    if normalized is ActionType.RE_LEARN:
        return "re_explain"
    return str(getattr(normalized, "value", normalized))


class QuestionDraft(StrictSchema):
    """Question content produced by a provider before persistence IDs are added."""

    schema_version: Literal["question-v0.1"] = "question-v0.1"
    concept: str = Field(min_length=1, max_length=100)
    question_text: str = Field(min_length=1, max_length=1000)
    coverage_points: list[str] = Field(min_length=2, max_length=5)
    difficulty: Literal["introductory", "intermediate", "advanced"]
    question_type: Literal["definition", "mechanism", "boundary", "transfer"]


class EvidenceItem(StrictSchema):
    """A claim tied to the shortest useful excerpt from the current answer."""

    evidence_id: str = Field(min_length=1)
    claim: str = Field(min_length=1, max_length=500)
    answer_excerpt: str = Field(min_length=1, max_length=500)
    strength: EvidenceStrength


class GapItem(StrictSchema):
    """Important content that the answer did not establish."""

    description: str = Field(min_length=1, max_length=500)
    severity: Severity


class MisconceptionItem(StrictSchema):
    """A possible incorrect claim that must have explicit answer evidence."""

    description: str = Field(min_length=1, max_length=500)
    confidence: float = Field(ge=0, le=1)
    answer_excerpt: str = Field(min_length=1, max_length=500)


class ProviderObservation(StrictSchema):
    """What the provider observed; this is not the user's final mastery state."""

    schema_version: Literal["provider-observation-v0.1"] = "provider-observation-v0.1"
    evidence: list[EvidenceItem]
    gaps: list[GapItem]
    possible_misconceptions: list[MisconceptionItem]
    observation_confidence: float = Field(
        ge=0,
        le=1,
        description="Confidence that the extracted observation is accurate, not a mastery score.",
    )
    limitations: list[str]


class MasteryDecision(StrictSchema):
    """A deterministic decision generated by a versioned Mastery Protocol."""

    schema_version: Literal["mastery-decision-v0.1", "mastery-decision-v0.2"] = (
        "mastery-decision-v0.2"
    )
    mastery_level: MasteryLevel
    understanding_level: UnderstandingLevel
    score: int = Field(ge=0, le=100)
    confidence: float = Field(ge=0, le=1)
    evidence_ids: list[str]
    reason: str = Field(min_length=1, max_length=1000)
    protocol_version: str = Field(min_length=1)

    @field_validator("mastery_level", mode="before")
    @classmethod
    def accept_legacy_mastery_level(cls, value: object) -> object:
        return normalize_mastery_level(value)

    @model_validator(mode="after")
    def levels_must_follow_the_demo_mapping(self) -> Self:
        """Prevent contradictory coarse and detailed levels in the v0.1 demo protocol."""
        expected = {
            MasteryLevel.NO_CLUE: UnderstandingLevel.NOVICE,
            MasteryLevel.FRAGILE: UnderstandingLevel.NOVICE,
            MasteryLevel.DEVELOPING: UnderstandingLevel.DEVELOPING,
            MasteryLevel.SOLID: UnderstandingLevel.PROFICIENT,
        }[self.mastery_level]
        if self.understanding_level is not expected:
            raise ValueError("understanding_level conflicts with mastery_level")
        return self


class LearningAction(StrictSchema):
    """One minimal action selected by a versioned deterministic policy."""

    schema_version: Literal["learning-action-v0.1", "learning-action-v0.2"] = "learning-action-v0.2"
    action_type: ActionType
    instruction: str = Field(min_length=1, max_length=1000)
    reason: str = Field(min_length=1, max_length=1000)
    evidence_ids: list[str]
    policy_version: str = Field(min_length=1)

    @field_validator("action_type", mode="before")
    @classmethod
    def accept_legacy_action_type(cls, value: object) -> object:
        return normalize_action_type(value)


class DiagnosisEnvelope(StrictSchema):
    """The final application contract consumed by persistence and UI."""

    schema_version: Literal["diagnosis-envelope-v0.1", "diagnosis-envelope-v0.2"] = (
        "diagnosis-envelope-v0.2"
    )
    observation: ProviderObservation
    decision: MasteryDecision
    next_action: LearningAction


def validate_answer_excerpts(observation: ProviderObservation, answer: str) -> None:
    """Reject provider evidence that does not appear verbatim in the current answer."""
    excerpts = [item.answer_excerpt for item in observation.evidence]
    excerpts.extend(item.answer_excerpt for item in observation.possible_misconceptions)
    missing = [excerpt for excerpt in excerpts if excerpt not in answer]
    if missing:
        raise ValueError("Provider evidence excerpt is not present in the user answer")
